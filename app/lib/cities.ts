export function findCity(name: string): { lat: number; lon: number } | null {
  const clean = name.replace(/\(.*?\)/g, '').trim();
  if (CITIES[clean]) return CITIES[clean];
  if (CITIES[name]) return CITIES[name];
  for (const [city, coord] of Object.entries(CITIES)) {
    if (clean.toLowerCase().includes(city.toLowerCase()) || city.toLowerCase().includes(clean.toLowerCase())) return coord;
  }
  return null;
}
